"""Write the title lists the collection checklist shows for books, magazines,
comics, newspapers, fliers and the rest of the game's titled literature.

A novel is one of a few item types (Base.Book_Fantasy, Base.Paperback_Horror)
and the game writes its title on each copy as it spawns, picked from registries
that live in the jar (zombie.scripting.objects.Book, Magazine, ComicBook...).
Lua can reach the registries but not the classes in them (they are not exposed)
and the registry's own ids are lower-cased, so the translation keys cannot be
rebuilt in game. This reads them out of the jar instead and writes

    DansVanillaFixes/42/media/lua/shared/DansVanillaFixes_CollectionTitles.lua

A title is registered when its id is a string constant in the registry's class
AND the English translation has the key made from it; the translation files alone
list a dozen books the game never registers. Rerun after a game update:

    python DansVanillaFixes/tools/gen_collection_titles.py           write the file
    python DansVanillaFixes/tools/gen_collection_titles.py --check   exit 1 if the file is out of date

The game is found like tests/check_api.py finds it: PZ_JAR, or the default
Steam folder. Without the game --check says so and passes.
"""
import json
import os
import struct
import sys
import zipfile

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "42", "media", "lua", "shared", "DansVanillaFixes_CollectionTitles.lua")
JAR = os.environ.get("PZ_JAR", r"C:\Program Files (x86)\Steam\steamapps\common\ProjectZomboid\projectzomboid.jar")
TRANSLATIONS = ("IG_UI.json", "Print_Media.json")

# registry class -> the translation key of one of its titles
# (shared/DansVanillaFixes_Collection.lua's TITLE_GROUPS has the same keys)
KINDS = [
    ("Book", "IGUI_BookTitle_{}"),
    ("RpgManual", "IGUI_RPG_{}"),
    ("Magazine", "IGUI_MagazineTitle_{}"),
    ("Catalogue", "IGUI_{}"),
    ("ComicBook", "IGUI_ComicTitle_{}"),
    ("OldNewspaper", "IGUI_NewspaperTitle_{}"),
    ("Newspaper", "Print_Media_{}_title"),      # one per issue
    ("Flier", "Print_Media_{}_title"),
    ("Brochure", "Print_Media_{}_title"),
]


def string_constants(data):
    """The CONSTANT_String values of a class file."""
    count = struct.unpack_from(">H", data, 8)[0]
    pos, utf8, strings, i = 10, {}, [], 1
    while i < count:
        tag = data[pos]
        if tag == 1:
            size = struct.unpack_from(">H", data, pos + 1)[0]
            utf8[i] = data[pos + 3:pos + 3 + size].decode("utf-8", "replace")
            pos += 3 + size
        elif tag in (5, 6):
            pos += 9
            i += 1          # longs and doubles take two slots
        else:
            if tag == 8:
                strings.append(struct.unpack_from(">H", data, pos + 1)[0])
            pos += {3: 5, 4: 5, 7: 3, 8: 3, 9: 5, 10: 5, 11: 5, 12: 5, 15: 4, 16: 3, 17: 5, 18: 5, 19: 3, 20: 3}[tag]
        i += 1
    return [utf8[s] for s in strings]


def read_game():
    media = os.path.join(os.path.dirname(JAR), "media", "lua", "shared", "Translate", "EN")
    keys = set()
    for name in TRANSLATIONS:
        with open(os.path.join(media, name), encoding="utf-8") as f:
            keys.update(json.load(f))
    out = {}
    with zipfile.ZipFile(JAR) as jar:
        for cls, key in KINDS:
            consts = string_constants(jar.read("zombie/scripting/objects/%s.class" % cls))
            out[cls] = sorted({c for c in consts if c and key.format(c) in keys}, key=lambda s: (s.lower(), s))
    return out


def lua(titles):
    lines = [
        "-- Dan's Vanilla Fixes: the titles of the game's books, magazines, comics,",
        "-- newspapers, fliers, brochures, catalogues and RPG manuals, for the collection",
        "-- checklist (shared/DansVanillaFixes_Collection.lua turns them into rows).",
        "--",
        "-- GENERATED by tools/gen_collection_titles.py from the game's jar: do not edit,",
        "-- rerun it after a game update. An id is the end of the title's translation key.",
        "",
        "DVF_CollectionTitles = {",
    ]
    for cls, _ in KINDS:
        ids = titles[cls]
        lines.append("    %s = {   -- %d" % (cls, len(ids)))
        row = "       "
        for name in ids:
            piece = ' "%s",' % name
            if len(row) + len(piece) > 110:
                lines.append(row)
                row = "       "
            row += piece
        if row.strip():
            lines.append(row)
        lines.append("    },")
    lines.append("}")
    return "\n".join(lines) + "\n"


def main():
    check = "--check" in sys.argv[1:]
    if not os.path.exists(JAR):
        print("gen_collection_titles: no game at %s (set PZ_JAR)" % JAR)
        return 0 if check else 1
    titles = read_game()
    text = lua(titles)
    summary = ", ".join("%s %d" % (cls, len(titles[cls])) for cls, _ in KINDS)
    if check:
        with open(OUT, encoding="utf-8") as f:
            same = f.read() == text
        print("gen_collection_titles: %s (%s)" % ("up to date" if same else "OUT OF DATE, rerun without --check", summary))
        return 0 if same else 1
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("gen_collection_titles: wrote %s (%s)" % (os.path.normpath(OUT), summary))
    return 0


if __name__ == "__main__":
    sys.exit(main())
