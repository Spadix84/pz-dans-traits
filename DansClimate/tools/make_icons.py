"""Draw the three Comfort moodle icons (client/DansClimate_ComfortClient.lua), in the
Vitality Project's style: a 16 x 16 grid of palette letters written out at 32 x 32.

    python DansClimate/tools/make_icons.py

Written to 42/media/ui and 42/media/ui/32 (Moodle Framework looks in the size folder
first), named after the moodle: ClimateChilly, ClimateStuffy, ClimateCosy.
"""
import os

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
MEDIA = os.path.join(HERE, "..", "42", "media")

PALETTE = {
    ".": (0, 0, 0, 0),
    "k": (30, 30, 30, 255),      # outline
    "w": (250, 250, 250, 255),
    "l": (195, 195, 195, 255),   # light grey
    "r": (205, 45, 45, 255),
    "o": (240, 140, 40, 255),
    "y": (250, 210, 60, 255),
    "b": (60, 120, 220, 255),
    "c": (130, 210, 235, 255),   # pale blue
    "n": (130, 90, 50, 255),     # brown
}

