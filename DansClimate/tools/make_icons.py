def draw(art):
    rows = [r for r in art.strip("\n").split("\n")]
    assert len(rows) == 16 and all(len(r) == 16 for r in rows), [len(r) for r in rows]
    im = Image.new("RGBA", (32, 32), (0, 0, 0, 0))
    for y, row in enumerate(rows):
        for x, ch in enumerate(row):
            for dx in (0, 1):
                for dy in (0, 1):
                    im.putpixel((2 * x + dx, 2 * y + dy), PALETTE[ch])
    return im


def main():
    for name, art in ICONS.items():
        im = draw(art)
        for folder in ("ui", os.path.join("ui", "32")):
            os.makedirs(os.path.join(MEDIA, folder), exist_ok=True)
            im.save(os.path.join(MEDIA, folder, name + ".png"))
    sheet = Image.new("RGBA", (32 * len(ICONS) * 4, 32 * 4), (70, 80, 70, 255))
    for i, art in enumerate(ICONS.values()):
        big = draw(art).resize((128, 128), Image.NEAREST)
        sheet.paste(big, (i * 128, 0), big)
    return sheet


if __name__ == "__main__":
    out = main()
    if len(os.sys.argv) > 1:
        out.save(os.sys.argv[1])
    print("wrote %d moodle icons" % len(ICONS))
